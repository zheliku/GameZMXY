using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Formatting;
using Microsoft.CodeAnalysis.Options;

namespace GameZmxy.Tools;

/// <summary>
/// Formats project-owned C# with Roslyn while preserving tokens, comments and initialization order.
/// </summary>
internal static class Program
{
    /// <summary>
    /// Audits all owned files, or formats them when --write is supplied; dependencies and generated files are excluded.
    /// </summary>
    /// <param name="args">Repository root, report path and optional --write.</param>
    private static void Main(string[] args)
    {
        string root = Path.GetFullPath(args[0]);
        string reportPath = Path.GetFullPath(args[1]);
        bool write = args.Contains("--write");
        var report = new List<object>();
        using var workspace = new AdhocWorkspace();
        OptionSet formatting = workspace.Options.WithChangedOption(FormattingOptions.UseTabs, LanguageNames.CSharp, false)
            .WithChangedOption(FormattingOptions.TabSize, LanguageNames.CSharp, 4)
            .WithChangedOption(FormattingOptions.IndentationSize, LanguageNames.CSharp, 4)
            .WithChangedOption(FormattingOptions.NewLine, LanguageNames.CSharp, "\r\n");
        foreach (string path in Directory.EnumerateFiles(root, "*.cs", SearchOption.AllDirectories))
        {
            string relative = Path.GetRelativePath(root, path).Replace('\\', '/');
            if (!IsOwned(relative))
            {
                continue;
            }

            string source = File.ReadAllText(path);
            if (Regex.IsMatch(source, @"(?m)^\s*//.*<auto-generated") ||
                Regex.IsMatch(source, @"(?m)^\s*///.*生成时会被覆盖，请勿手动修改"))
            {
                continue;
            }

            var options = new CSharpParseOptions(LanguageVersion.Preview, preprocessorSymbols: ["DEBUG", "ENABLE_LOG", "ENABLE_INFO_AND_ABOVE_LOG"]);
            SyntaxNode original = CSharpSyntaxTree.ParseText(source, options).GetRoot();
            if (original.GetDiagnostics().Any(issue => issue.Severity == DiagnosticSeverity.Error))
            {
                throw new InvalidOperationException("Cannot format invalid syntax: " + relative);
            }

            SyntaxNode rewritten = new StyleRewriter().Visit(original)!;
            VerifyTokens(original, rewritten);
            string formatted = Formatter.Format(rewritten, workspace, formatting).ToFullString().TrimEnd() + "\r\n";
            formatted = Regex.Replace(formatted, @"(?m)^([ \t]*)/// <summary>([^\r\n]+)</summary>\r?$",
                match => match.Groups[1].Value + "/// <summary>\r\n" + match.Groups[1].Value + "/// " +
                         match.Groups[2].Value.Trim() + "\r\n" + match.Groups[1].Value + "/// </summary>");
            SyntaxNode verified = CSharpSyntaxTree.ParseText(formatted, options).GetRoot();
            VerifyTokens(rewritten, verified);
            VerifyComments(original, verified);
            if (verified.GetDiagnostics().Any(issue => issue.Severity == DiagnosticSeverity.Error))
            {
                throw new InvalidOperationException("Formatter produced invalid syntax: " + relative);
            }

            string[] missing = original.DescendantNodes().OfType<MemberDeclarationSyntax>()
                .Where(NeedsDocumentation)
                .Where(member => !member.GetLeadingTrivia().Any(trivia => trivia.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia)))
                .Select(member => $"{member.GetLocation().GetLineSpan().StartLinePosition.Line + 1}: {member.ToString().Split('\n')[0].Trim()}")
                .ToArray();
            bool changed = source != formatted;
            report.Add(new
            {
                path = relative,
                changed,
                missingDocumentation = missing,
                beforeSha256 = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(source)))
            });
            if (write && changed)
            {
                File.WriteAllText(path, formatted, new UTF8Encoding(false));
            }
        }

        Directory.CreateDirectory(Path.GetDirectoryName(reportPath)!);
        File.WriteAllText(reportPath, JsonSerializer.Serialize(report, new JsonSerializerOptions { WriteIndented = true }));
        Console.WriteLine($"C# STYLE {(write ? "WRITE" : "AUDIT")} PASS: {report.Count} owned files; token preservation verified. Report: {reportPath}");
    }

    /// <summary>
    /// Limits changes to handwritten game, editor, test and maintenance sources.
    /// </summary>
    /// <param name="path">相对仓库根的规范化文件路径。</param>
    /// <returns>文件是否属于本工具允许修改的手写代码范围。</returns>
    private static bool IsOwned(string path)
    {
        string[] excluded = ["/.godot/", "/bin/", "/obj/", "/node_modules/", "/Framework/", "/addons/", "/GameProto/", "Tools/Luban/", "/.git/"];
        return !excluded.Any(path.Contains) &&
               (path.StartsWith("Godot/GodotProject/TheGame/") || path.StartsWith("Godot/GodotProject/EditorScripts/") ||
                path.StartsWith("Tests/") || path.StartsWith("Tools/ProjectMaintenance/"));
    }

    /// <summary>
    /// Private fields retain concise trailing comments; callable members and types need XML documentation.
    /// </summary>
    /// <param name="member">待分类或检查的C#成员声明。</param>
    /// <returns>声明是否需要独立的XML调用契约。</returns>
    private static bool NeedsDocumentation(MemberDeclarationSyntax member)
    {
        if (member is ExtensionBlockDeclarationSyntax)
        {
            return false;
        }

        return member is BaseTypeDeclarationSyntax or BaseMethodDeclarationSyntax or PropertyDeclarationSyntax or
            IndexerDeclarationSyntax or EventDeclarationSyntax or DelegateDeclarationSyntax;
    }

    /// <summary>
    /// Rejects formatting that would lose or duplicate comments, including namespace-semicolon trivia.
    /// </summary>
    /// <param name="before">转换前的原始语法树。</param>
    /// <param name="after">转换后的待验证语法树。</param>
    private static void VerifyComments(SyntaxNode before, SyntaxNode after)
    {
        static string[] Inventory(SyntaxNode node)
        {
            return node.DescendantTrivia().Where(trivia => trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) ||
                trivia.IsKind(SyntaxKind.MultiLineCommentTrivia) || trivia.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia))
                .Select(trivia => Regex.Replace(trivia.ToFullString().Replace("///", ""), @"\s+", ""))
                .Order().ToArray();
        }

        if (!Inventory(before).SequenceEqual(Inventory(after)))
        {
            throw new InvalidOperationException("Formatter changed comment content.");
        }
    }

    /// <summary>
    /// Checks that only block braces and a file-scoped namespace semicolon can change.
    /// </summary>
    /// <param name="before">转换前的原始语法树。</param>
    /// <param name="after">转换后的待验证语法树。</param>
    private static void VerifyTokens(SyntaxNode before, SyntaxNode after)
    {
        static Dictionary<string, int> Inventory(SyntaxNode node)
        {
            var namespaceSemicolons = node.DescendantNodes().OfType<FileScopedNamespaceDeclarationSyntax>()
                .Select(item => item.SemicolonToken).ToHashSet();
            return node.DescendantTokens().Where(token => !token.IsKind(SyntaxKind.OpenBraceToken) &&
                !token.IsKind(SyntaxKind.CloseBraceToken) && !namespaceSemicolons.Contains(token))
                .GroupBy(token => token.RawKind + ":" + token.Text).ToDictionary(group => group.Key, group => group.Count());
        }

        Dictionary<string, int> first = Inventory(before);
        Dictionary<string, int> second = Inventory(after);
        if (first.Count != second.Count || first.Any(pair => !second.TryGetValue(pair.Key, out int count) || pair.Value != count))
        {
            throw new InvalidOperationException("Formatter changed non-structural tokens.");
        }
    }

    /// <summary>
    /// Normalizes namespace and statement blocks without renaming APIs or reordering initializers.
    /// </summary>
    private sealed class StyleRewriter : CSharpSyntaxRewriter
    {
        /// <summary>
        /// Keeps a blank separator before non-field members without changing initialization order.
        /// </summary>
        /// <param name="node">待保留语义并规范格式的语法节点。</param>
        /// <returns>保持初始化次序的成员排序结果。</returns>
        public override SyntaxNode? VisitClassDeclaration(ClassDeclarationSyntax node)
        {
            var value = (ClassDeclarationSyntax)base.VisitClassDeclaration(node)!;
            SyntaxList<MemberDeclarationSyntax> ordered = value.Members;
            if (!value.DescendantTrivia().Any(trivia => trivia.IsDirective))
            {
                SyntaxList<MemberDeclarationSyntax> candidate = SyntaxFactory.List(value.Members.OrderBy(MemberOrder));
                // Auto-property and field initializers can depend on their textual order.
                // Reorder members only when that runtime initialization sequence stays identical.
                if (value.Members.Where(HasInitializer).SequenceEqual(candidate.Where(HasInitializer)))
                {
                    ordered = candidate;
                }
            }

            IEnumerable<MemberDeclarationSyntax> members = ordered.Select((member, index) => NormalizeLeading(member, index == 0));
            return value.WithMembers(SyntaxFactory.List(members));
        }

        /// <summary>
        /// Removes empty lines before the first declaration in a block namespace.
        /// </summary>
        /// <param name="node">Namespace whose member trivia is being normalized.</param>
        /// <returns>The namespace with its declarations and comments preserved.</returns>
        public override SyntaxNode? VisitNamespaceDeclaration(NamespaceDeclarationSyntax node)
        {
            var value = (NamespaceDeclarationSyntax)base.VisitNamespaceDeclaration(node)!;
            return value.WithMembers(SyntaxFactory.List(value.Members.Select((member, index) => NormalizeLeading(member, index == 0))));
        }

        /// <summary>
        /// Keeps at most one blank separator without changing comments or directive placement.
        /// </summary>
        /// <param name="member">Declaration whose leading whitespace is being normalized.</param>
        /// <param name="first">Whether the declaration is the first in its containing block.</param>
        /// <returns>The declaration with normalized leading whitespace.</returns>
        private static MemberDeclarationSyntax NormalizeLeading(MemberDeclarationSyntax member, bool first)
        {
            SyntaxTriviaList leading = member.GetLeadingTrivia();
            SyntaxTrivia[] whitespace = leading.TakeWhile(trivia => trivia.IsKind(SyntaxKind.WhitespaceTrivia) || trivia.IsKind(SyntaxKind.EndOfLineTrivia)).ToArray();
            SyntaxTriviaList result = SyntaxFactory.TriviaList(leading.Skip(whitespace.Length));
            if (whitespace.LastOrDefault().IsKind(SyntaxKind.WhitespaceTrivia))
            {
                result = result.Insert(0, whitespace[^1]);
            }

            if (!first && (member is not FieldDeclarationSyntax || whitespace.Any(trivia => trivia.IsKind(SyntaxKind.EndOfLineTrivia))))
            {
                result = result.Insert(0, SyntaxFactory.EndOfLine("\r\n"));
            }

            return member.WithLeadingTrivia(result);
        }

        /// <summary>
        /// Keeps storage before constructors, properties, events, methods and nested declarations.
        /// </summary>
        /// <param name="member">待分类或检查的C#成员声明。</param>
        /// <returns>字段、构造、属性、事件、方法和配套类型的排序键。</returns>
        private static int MemberOrder(MemberDeclarationSyntax member)
        {
            return member switch
            {
                FieldDeclarationSyntax => 0,
                ConstructorDeclarationSyntax => 1,
                PropertyDeclarationSyntax or IndexerDeclarationSyntax => 2,
                EventDeclarationSyntax or EventFieldDeclarationSyntax => 3,
                BaseMethodDeclarationSyntax => 4,
                _ => 5
            };
        }

        /// <summary>
        /// Detects initializers whose textual order affects construction or type initialization.
        /// </summary>
        /// <param name="member">待分类或检查的C#成员声明。</param>
        /// <returns>声明是否包含必须保留文本先后顺序的初始化表达式。</returns>
        private static bool HasInitializer(MemberDeclarationSyntax member)
        {
            return member switch
            {
                FieldDeclarationSyntax field => field.Declaration.Variables.Any(item => item.Initializer != null),
                EventFieldDeclarationSyntax field => field.Declaration.Variables.Any(item => item.Initializer != null),
                PropertyDeclarationSyntax property => property.Initializer != null,
                _ => false
            };
        }

        /// <summary>
        /// Converts a file-scoped namespace to the block form used by UGF.
        /// </summary>
        /// <param name="node">待保留语义并规范格式的语法节点。</param>
        /// <returns>保留原声明和注释的块形式命名空间。</returns>
        public override SyntaxNode? VisitFileScopedNamespaceDeclaration(FileScopedNamespaceDeclarationSyntax node)
        {
            var visited = (FileScopedNamespaceDeclarationSyntax)base.VisitFileScopedNamespaceDeclaration(node)!;
            NamespaceDeclarationSyntax value = SyntaxFactory.NamespaceDeclaration(visited.Name).WithAttributeLists(visited.AttributeLists)
                .WithExterns(visited.Externs).WithUsings(visited.Usings).WithMembers(visited.Members)
                .WithLeadingTrivia(visited.GetLeadingTrivia()).WithTrailingTrivia(visited.GetTrailingTrivia());
            return value.WithMembers(SyntaxFactory.List(value.Members.Select((member, index) => NormalizeLeading(member, index == 0))));
        }

        /// <summary>
        /// Braces conditional branches; else-if remains a continuous branch chain.
        /// </summary>
        /// <param name="node">待保留语义并规范格式的语法节点。</param>
        /// <returns>条件分支补齐大括号后的节点。</returns>
        public override SyntaxNode? VisitIfStatement(IfStatementSyntax node)
        {
            var value = (IfStatementSyntax)base.VisitIfStatement(node)!;
            value = value.WithStatement(Block(value.Statement));
            if (value.Else is { Statement: not IfStatementSyntax } other)
            {
                value = value.WithElse(other.WithStatement(Block(other.Statement)));
            }

            return value;
        }

        /// <summary>
        /// Braces for loops.
        /// </summary>
        /// <param name="node">待保留语义并规范格式的语法节点。</param>
        /// <returns>循环体补齐大括号后的节点。</returns>
        public override SyntaxNode? VisitForStatement(ForStatementSyntax node)
        {
            var value = (ForStatementSyntax)base.VisitForStatement(node)!;
            return value.WithStatement(Block(value.Statement));
        }

        /// <summary>
        /// Braces foreach loops.
        /// </summary>
        /// <param name="node">待保留语义并规范格式的语法节点。</param>
        /// <returns>循环体补齐大括号后的节点。</returns>
        public override SyntaxNode? VisitForEachStatement(ForEachStatementSyntax node)
        {
            var value = (ForEachStatementSyntax)base.VisitForEachStatement(node)!;
            return value.WithStatement(Block(value.Statement));
        }

        /// <summary>
        /// Braces tuple foreach loops.
        /// </summary>
        /// <param name="node">待保留语义并规范格式的语法节点。</param>
        /// <returns>解构循环体补齐大括号后的节点。</returns>
        public override SyntaxNode? VisitForEachVariableStatement(ForEachVariableStatementSyntax node)
        {
            var value = (ForEachVariableStatementSyntax)base.VisitForEachVariableStatement(node)!;
            return value.WithStatement(Block(value.Statement));
        }

        /// <summary>
        /// Braces while loops.
        /// </summary>
        /// <param name="node">待保留语义并规范格式的语法节点。</param>
        /// <returns>循环体补齐大括号后的节点。</returns>
        public override SyntaxNode? VisitWhileStatement(WhileStatementSyntax node)
        {
            var value = (WhileStatementSyntax)base.VisitWhileStatement(node)!;
            return value.WithStatement(Block(value.Statement));
        }

        /// <summary>
        /// Preserves existing blocks and empty loops; wraps other statements in a lexical block.
        /// </summary>
        /// <param name="statement">待补全大括号的原始语句。</param>
        /// <returns>原有块、空语句或包裹原语句的新块。</returns>
        private static StatementSyntax Block(StatementSyntax statement) => statement is BlockSyntax or EmptyStatementSyntax ? statement : SyntaxFactory.Block(statement);
    }
}
